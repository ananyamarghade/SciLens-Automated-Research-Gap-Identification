    def export_literature_review_to_markdown(self, lit_review: dict, topic: str = "Research Topic") -> bytes:
        """Exports a LiteratureReviewResponse dictionary to Markdown."""
        lines = [
            f"# Systematic Literature Review: {topic}",
            "",
            f"> *Organization: {lit_review.get('organization', 'Thematic')} • Citation Style: {lit_review.get('citation_style', 'APA 7')} • Depth: {lit_review.get('review_depth', 'Detailed')}*",
            "",
            "---",
            "",
        ]

        for sec in lit_review.get("sections", []):
            lines.append(f"## {sec.get('title', 'Section')}")
            lines.append("")
            lines.append(sec.get("content", ""))
            lines.append("")

        for table_data in lit_review.get("tables", []):
            t_title = table_data.get("title", "Comparative Matrix")
            lines.append(f"### {t_title}")
            lines.append("")
            headers = table_data.get("headers", [])
            rows = table_data.get("rows", [])
            if headers:
                lines.append("| " + " | ".join(headers) + " |")
                lines.append("| " + " | ".join(["---"] * len(headers)) + " |")
                for r in rows:
                    lines.append("| " + " | ".join(str(c) for c in r) + " |")
            lines.append("")

        return "\n".join(lines).encode("utf-8")

